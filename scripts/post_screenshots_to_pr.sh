#!/usr/bin/env bash
# Posts (or updates) a sticky comment on the PR with a screenshot gallery.
# Screenshots are PNGs pulled from the emulator by the workflow into
# ./screenshots. The repo is public, so raw.githubusercontent.com URLs
# render inline in the PR. Falls back to artifact links if the branch push
# is unavailable.
set -u

REPO="${REPO:-}"
PR_NUMBER="${PR_NUMBER:-}"
SCREENSHOT_DIR="${SCREENSHOT_DIR:-./screenshots}"
BRANCH="ci-screenshots"
COMMENT_TAG="<!-- ohaa-screenshot-gallery -->"

if [ -z "$REPO" ] || [ -z "$PR_NUMBER" ]; then
  echo "REPO and PR_NUMBER are required" >&2
  exit 1
fi

# Collect PNGs, sorted, one line each: name|path
mapfile -t PNGS < <(find "$SCREENSHOT_DIR" -name '*.png' | sort)
if [ ${#PNGS[@]} -eq 0 ]; then
  echo "No screenshots found in $SCREENSHOT_DIR" >&2
  exit 1
fi

# Push screenshots to a dedicated branch so the gallery has stable public URLs.
TMP=$(mktemp -d)
git clone -q --depth 1 "https://x-access-token:${GITHUB_TOKEN}@github.com/${REPO}.git" "$TMP" -b "$BRANCH" 2>/dev/null \
  || git clone -q --depth 1 "https://x-access-token:${GITHUB_TOKEN}@github.com/${REPO}.git" "$TMP"
cd "$TMP"
git checkout -q -B "$BRANCH" 2>/dev/null || true
mkdir -p screenshots
for p in "${PNGS[@]}"; do cp "$p" "screenshots/$(basename "$p")"; done
git add screenshots
git -c user.name="github-actions[bot]" -c user.email="github-actions[bot]@users.noreply.github.com" \
  commit -q -m "ci: update UI screenshots (run ${GITHUB_RUN_ID:-local})" || echo "nothing to commit"
git push -q origin "$BRANCH" 2>/dev/null || echo "WARN: could not push screenshot branch"
cd - >/dev/null

RAW_BASE="https://raw.githubusercontent.com/${REPO}/${BRANCH}/screenshots"

# Build the markdown gallery
BODY="${COMMENT_TAG}
### 📱 Live UI screenshots (emulator, API 30 x86_64)
Run: \`${GITHUB_RUN_ID:-?}\` · commit: \`${GITHUB_SHA:-?}\`

"
for p in "${PNGS[@]}"; do
  name="$(basename "$p" .png)"
  BODY+="<details><summary><b>${name}</b></summary><br>
<img src=\"${RAW_BASE}/$(basename "$p")\" width=\"320\"/>
</details>

"
done
BODY+="
_Generated by an AI agent (OpenHands) on behalf of the repo owner._"

# Find an existing comment with our tag and update it, else create one.
EXISTING=$(curl -s -H "Authorization: Bearer $GITHUB_TOKEN" \
  -H "Accept: application/vnd.github+json" \
  "https://api.github.com/repos/${REPO}/issues/${PR_NUMBER}/comments?per_page=100" \
  | python3 -c "
import json,sys
tag='${COMMENT_TAG}'
for c in json.load(sys.stdin):
    if tag in c.get('body',''):
        print(c['id']); break
")

PAYLOAD=$(python3 -c "import json,sys; print(json.dumps({'body': sys.stdin.read()}))" <<< "$BODY")

if [ -n "$EXISTING" ]; then
  curl -s -o /dev/null -w "updated comment %{http_code}\n" -X PATCH \
    -H "Authorization: Bearer $GITHUB_TOKEN" -H "Accept: application/vnd.github+json" \
    -H "Content-Type: application/json" \
    "https://api.github.com/repos/${REPO}/issues/comments/${EXISTING}" -d "$PAYLOAD"
else
  curl -s -o /dev/null -w "created comment %{http_code}\n" -X POST \
    -H "Authorization: Bearer $GITHUB_TOKEN" -H "Accept: application/vnd.github+json" \
    -H "Content-Type: application/json" \
    "https://api.github.com/repos/${REPO}/issues/${PR_NUMBER}/comments" -d "$PAYLOAD"
fi
